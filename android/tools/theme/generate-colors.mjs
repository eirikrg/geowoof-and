// Generates ColorSchemes.kt for :core:designsystem with the same algorithm as Material Theme Builder,
// for light and dark themes at standard, medium and high contrast. The colors come from the icon of the
// app: a primary and neutrals from its sage green, and a warm clay as the accent (docs/design/README.md).
//
//   cd android/tools/theme && npm ci && node generate-colors.mjs [output-file]
import { writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import {
  argbFromHex,
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  TonalPalette,
} from '@material/material-color-utilities';

// Variant.TONAL_SPOT: the package has it, but does not export it.
const TONAL_SPOT = 2;

// Measured on the icon.
const SAGE = '#729578';
const FOREST = '#214233';
// Chosen to go with them: the earth of a path.
const CLAY = '#C4703F';

const brandHue = Hct.fromInt(argbFromHex(SAGE)).hue;
const clayHct = Hct.fromInt(argbFromHex(CLAY));

const palettes = {
  primaryPalette: TonalPalette.fromHueAndChroma(brandHue, 30),
  secondaryPalette: TonalPalette.fromHueAndChroma(brandHue, 13),
  tertiaryPalette: TonalPalette.fromHueAndChroma(clayHct.hue, 44),
  neutralPalette: TonalPalette.fromHueAndChroma(brandHue, 4),
  neutralVariantPalette: TonalPalette.fromHueAndChroma(brandHue, 8),
};

const output = process.argv[2]
  ? pathToFileURL(process.argv[2])
  : new URL('../../core/designsystem/src/main/kotlin/com/geowoof/core/designsystem/theme/ColorSchemes.kt', import.meta.url);

// Roles of androidx.compose.material3.ColorScheme, in declaration order.
const roles = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim',
  'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
];

const hex = (argb) => '0xFF' + (argb & 0xffffff).toString(16).padStart(6, '0').toUpperCase();
const kotlinColor = (value) => `0xFF${value.slice(1).toUpperCase()}`;

const schemes = [
  ['LightColorScheme', false, 0.0],
  ['LightMediumContrastColorScheme', false, 0.5],
  ['LightHighContrastColorScheme', false, 1.0],
  ['DarkColorScheme', true, 0.0],
  ['DarkMediumContrastColorScheme', true, 0.5],
  ['DarkHighContrastColorScheme', true, 1.0],
];

let kotlin = `// Generated by android/tools/theme/generate-colors.mjs from the colors of the icon: sage ${SAGE},
// forest ${FOREST} and clay ${CLAY} (Material Theme Builder algorithm). Do not edit by hand; regenerate instead.
package com.geowoof.core.designsystem.theme

import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.ui.graphics.Color

/** The two greens of the icon, exactly: only for what has to look like the logo. */
internal val BrandSage = Color(${kotlinColor(SAGE)})
internal val BrandForest = Color(${kotlinColor(FOREST)})
`;

for (const [name, isDark, contrast] of schemes) {
  const scheme = new DynamicScheme({
    sourceColorArgb: argbFromHex(SAGE),
    variant: TONAL_SPOT,
    contrastLevel: contrast,
    isDark,
    ...palettes,
  });
  const builder = isDark ? 'darkColorScheme' : 'lightColorScheme';
  kotlin += `\ninternal val ${name} = ${builder}(\n`;
  for (const role of roles) {
    const color = role === 'surfaceTint' ? MaterialDynamicColors.primary : MaterialDynamicColors[role];
    kotlin += `    ${role} = Color(${hex(color.getArgb(scheme))}),\n`;
  }
  kotlin += ')\n';
}

writeFileSync(output, kotlin);
console.log(`Wrote ${output.pathname}`);
